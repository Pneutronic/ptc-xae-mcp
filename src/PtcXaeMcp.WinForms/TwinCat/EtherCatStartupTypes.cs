namespace PtcXaeMcp.WinForms.TwinCat;

internal static class EtherCatStartupProtocol
{
    public const string CoE = "CoE", SoE = "SoE", EoE = "EoE", FoE = "FoE";

    private static readonly string[] All = [CoE, SoE, EoE, FoE];

    /// <summary>Case-insensitive; null or empty means "all" (result null). False for an unknown protocol.</summary>
    public static bool TryNormalize(string? text, out string? protocol)
    {
        protocol = null;
        string s = (text ?? string.Empty).Trim();
        if (s.Length == 0) return true;
        protocol = All.FirstOrDefault(p => p.Equals(s, StringComparison.OrdinalIgnoreCase));
        return protocol is not null;
    }

    public static string Names => string.Join(", ", All);
}

/// <summary>Length header of a SoE list parameter: UINT16 actual length, UINT16 maximum length (bytes).</summary>
internal sealed record SoeListHeader(int CurrentLength, int MaxLength);

internal sealed record EtherCatEoeVirtualPort(
    string? MacAddr, string? IpAddr, string? Subnet, string? Gateway, string? DnsAddr, string? DnsName);

/// <summary>
/// One entry of the Startup tab. The common fields are set for every protocol; the CoE, SoE and the EoE/FoE specific
/// ones stay null for the others. <see cref="Fixed"/> entries are generated by TwinCAT (shown in angle brackets).
/// </summary>
internal sealed record EtherCatStartupEntry(
    string Protocol, bool Fixed, IReadOnlyList<string> Transitions, string? Comment, int? TimeoutMs, string DataHex,
    // CoE
    string? Index = null, string? SubIndex = null, bool? CompleteAccess = null, string? Source = null,
    // SoE
    string? Idn = null, int? IdnRaw = null, int? ParameterSet = null, int? DriveNo = null, int? OpCode = null,
    string? Elements = null, int? Attribute = null, ulong? Value = null, SoeListHeader? List = null,
    IReadOnlyList<string>? IdnList = null);

internal sealed record EtherCatStartupBox(
    string TreePath, string Name, string SlaveType, int? PhysAddr, string? LinkedAxis, int? SoeChannels,
    EtherCatEoeVirtualPort? VirtualPort, IReadOnlyList<EtherCatStartupEntry> Entries);

internal sealed record EtherCatStartupResult(IReadOnlyList<EtherCatStartupBox> Boxes, int SlavesScanned)
{
    public int EntryCount => Boxes.Sum(b => b.Entries.Count);

    public int FixedCount => Boxes.Sum(b => b.Entries.Count(e => e.Fixed));

    public int CountByProtocol(string protocol) => Boxes.Sum(b => b.Entries.Count(e => e.Protocol == protocol));
}
