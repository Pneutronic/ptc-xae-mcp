using System.Text.RegularExpressions;

namespace PtcXaeMcp.WinForms.TwinCat;

/// <summary>
/// What kind of projects a .sln declares, read from its Project(...) lines. Used by
/// open_project to tell an HMI-only solution (TE2000, no .tsproj) apart from a TwinCAT
/// solution: waiting for a System Manager there cost 120 s and ended in an [Error] although
/// the solution was open (seen live 2026-09-25 with HMI-only fixture solutions).
/// </summary>
internal static partial class SolutionFile
{
    [GeneratedRegex(@"^Project\(""\{[0-9A-Fa-f-]+\}""\)\s*=\s*""[^""]*""\s*,\s*""([^""]+)""", RegexOptions.Multiline)]
    private static partial Regex ProjectLine();

    internal readonly record struct Kinds(bool HasTwinCat, bool HasHmi);

    public static Kinds Classify(string slnText)
    {
        bool twinCat = false, hmi = false;
        foreach (Match m in ProjectLine().Matches(slnText))
        {
            string path = m.Groups[1].Value;
            if (path.EndsWith(".tsproj", StringComparison.OrdinalIgnoreCase) ||
                path.EndsWith(".tspproj", StringComparison.OrdinalIgnoreCase)) twinCat = true;
            else if (path.EndsWith(".hmiproj", StringComparison.OrdinalIgnoreCase)) hmi = true;
        }
        return new Kinds(twinCat, hmi);
    }

    private const string TwinCatTypeGuid = "{B1E792BE-AA5F-4E3C-8C82-674BF9C0715B}";
    private const string HmiTypeGuid = "{FE7A1B72-C5B7-4D7C-BB7D-76384D4DE8E1}";

    public static bool IsSolution(string path) => path.EndsWith(".sln", StringComparison.OrdinalIgnoreCase);

    public static bool IsProjectFile(string path) =>
        path.EndsWith(".tsproj", StringComparison.OrdinalIgnoreCase) ||
        path.EndsWith(".tspproj", StringComparison.OrdinalIgnoreCase) ||
        path.EndsWith(".hmiproj", StringComparison.OrdinalIgnoreCase) ||
        IsPlcProject(path);

    /// <summary>A bare PLC project (e.g. a library repository without a TwinCAT project around it).</summary>
    public static bool IsPlcProject(string path) => path.EndsWith(".plcproj", StringComparison.OrdinalIgnoreCase);

    private const string StandalonePlcTypeGuid = "{DFBE7525-6864-4E62-8B2E-D530D69D9D96}";

    // Generated solution directory -> the project file it was generated for. Kept in this process only: the
    // path policy widens its allowed roots by it, so it must not come from a file a tool could write.
    private static readonly System.Collections.Concurrent.ConcurrentDictionary<string, string> GeneratedSources =
        new(StringComparer.OrdinalIgnoreCase);

    /// <summary>
    /// The project file a solution generated by <see cref="ResolveSolution"/> in this process stands for
    /// (.tsproj, .tspproj, .hmiproj or .plcproj); null for any other solution or directory.
    /// </summary>
    public static string? SourceOfGenerated(string? solutionPathOrDirectory)
    {
        if (string.IsNullOrWhiteSpace(solutionPathOrDirectory) || GeneratedSources.IsEmpty) return null;
        string? dir = IsSolution(solutionPathOrDirectory.Trim().Trim('"'))
            ? Path.GetDirectoryName(solutionPathOrDirectory.Trim().Trim('"'))
            : solutionPathOrDirectory;
        // Both sides normalized: %TEMP% can come as an 8.3 short path, the XAE reports the long one.
        return SolutionPathMatch.Normalize(dir) is { } key && GeneratedSources.TryGetValue(key, out string? source) ? source : null;
    }

    /// <summary>
    /// The stand-alone PLC project (.tspproj) the XAE needs around a bare .plcproj: it loads a PLC project only
    /// inside a TwinCAT project. The .plcproj stays where it is (absolute PrjFilePath, live-checked on TC 3.1.4026.22:
    /// the tree loads, edits are saved into the .plcproj's own files, the build output goes next to the wrapper).
    /// </summary>
    public static string StandaloneWrapperFor(string plcprojPath, string wrapperGuid)
    {
        string name = Path.GetFileNameWithoutExtension(plcprojPath);
        string plcGuid = "{" + Guid.NewGuid().ToString().ToUpperInvariant() + "}";
        string tcVersion = "3.1.4026.22";
        try
        {
            var doc = System.Xml.Linq.XDocument.Load(plcprojPath);
            var ns = doc.Root?.Name.Namespace ?? System.Xml.Linq.XNamespace.None;
            // Only the project's own properties: item groups (library references, …) carry elements of the same name.
            var props = doc.Root?.Elements(ns + "PropertyGroup").SelectMany(g => g.Elements()).ToList() ?? [];
            string? Prop(string name) => props.FirstOrDefault(e => e.Name == ns + name)?.Value.Trim();
            string? guid = Prop("ProjectGuid");
            if (Guid.TryParse(guid, out var g)) plcGuid = g.ToString("B").ToUpperInvariant();
            string? version = Prop("ProgramVersion");
            if (version is not null && Regex.IsMatch(version, @"^\d+(\.\d+){1,3}$")) tcVersion = version;
            string? plcName = Prop("Name");
            if (!string.IsNullOrEmpty(plcName)) name = plcName;
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or System.Xml.XmlException) { }

        static string Attr(string s) => System.Security.SecurityElement.Escape(s);
        string tmc = Path.ChangeExtension(plcprojPath, ".tmc");
        return string.Join("\r\n",
            "<?xml version=\"1.0\"?>",
            "<TcSmProject xmlns:xsi=\"http://www.w3.org/2001/XMLSchema-instance\" xsi:noNamespaceSchemaLocation=\"http://www.beckhoff.com/schemas/2012/07/TcSmProject\" " +
            $"TcSmVersion=\"1.0\" TcVersion=\"{Attr(tcVersion)}\">",
            $"\t<Project ProjectGUID=\"{wrapperGuid}\" Target64Bit=\"true\" ShowHideConfigurations=\"#x6\">",
            "\t\t<Plc>",
            $"\t\t\t<Project GUID=\"{plcGuid}\" Name=\"{Attr(name)}\" PrjFilePath=\"{Attr(plcprojPath)}\" TmcFilePath=\"{Attr(tmc)}\" " +
            "ReloadTmc=\"true\" AmsPort=\"851\" FileArchiveSettings=\"#x000e\" SymbolicMapping=\"true\"/>",
            "\t\t</Plc>",
            "\t</Project>",
            "</TcSmProject>",
            "");
    }

    /// <summary>Project paths a solution declares, as written (possibly relative to the .sln).</summary>
    public static IEnumerable<string> ProjectPaths(string slnText) =>
        ProjectLine().Matches(slnText).Select(m => m.Groups[1].Value);

    /// <summary>
    /// The text of a one-project solution. Teams commit the project file (.tsproj / .hmiproj)
    /// and gitignore the .sln, so open_project builds this throwaway solution around it.
    /// </summary>
    public static string SolutionTextFor(string projectPath)
    {
        string typeGuid = projectPath.EndsWith(".hmiproj", StringComparison.OrdinalIgnoreCase) ? HmiTypeGuid
            : projectPath.EndsWith(".tspproj", StringComparison.OrdinalIgnoreCase) ? StandalonePlcTypeGuid
            : TwinCatTypeGuid;
        string name = Path.GetFileNameWithoutExtension(projectPath);
        string projectGuid = ProjectGuidFor(projectPath);
        return string.Join("\r\n",
            "Microsoft Visual Studio Solution File, Format Version 12.00",
            "# TcXaeShell Solution File, Format Version 11.00",
            $"Project(\"{typeGuid}\") = \"{name}\", \"{projectPath}\", \"{projectGuid}\"",
            "EndProject", "");
    }

    /// <summary>
    /// A .sln path is returned as is. A project file gets a generated solution under
    /// %TEMP%\ptc-xae-mcp\solutions\&lt;hash&gt; (rewritten on every call, so it never goes stale).
    /// </summary>
    public static string ResolveSolution(string path)
    {
        if (IsSolution(path)) return path;
        string full = Path.GetFullPath(path);
        var hash = System.Security.Cryptography.SHA256.HashData(
            System.Text.Encoding.UTF8.GetBytes(full.ToLowerInvariant()));
        string dir = Path.Combine(Path.GetTempPath(), "ptc-xae-mcp", "solutions",
            Convert.ToHexString(hash, 0, 4));
        Directory.CreateDirectory(dir);
        string sln = Path.Combine(dir, Path.GetFileNameWithoutExtension(full) + ".sln");

        if (IsPlcProject(full))
        {
            // A bare .plcproj opens inside a generated stand-alone PLC project. Both files are written only when
            // missing or pointing elsewhere: the XAE rewrites the .sln on load, and rewriting a file it has open
            // raises its "changed outside the environment" prompt.
            string wrapper = Path.Combine(dir, Path.GetFileNameWithoutExtension(full) + ".tspproj");
            string wrapperGuid = ProjectGuidFor(wrapper);
            if (!File.Exists(wrapper) || !File.ReadAllText(wrapper).Contains(
                    $"PrjFilePath=\"{System.Security.SecurityElement.Escape(full)}\"", StringComparison.OrdinalIgnoreCase))
            {
                File.WriteAllText(wrapper, StandaloneWrapperFor(full, wrapperGuid));
                File.WriteAllText(sln, SolutionTextFor(wrapper));
            }
            else if (!File.Exists(sln)) File.WriteAllText(sln, SolutionTextFor(wrapper));
        }
        else File.WriteAllText(sln, SolutionTextFor(full));

        if (SolutionPathMatch.Normalize(dir) is { } key) GeneratedSources[key] = full;
        return sln;
    }

    private static string ProjectGuidFor(string projectPath)
    {
        var hash = System.Security.Cryptography.SHA256.HashData(
            System.Text.Encoding.UTF8.GetBytes(projectPath.ToLowerInvariant()));
        return new Guid(hash.AsSpan(0, 16)).ToString("B").ToUpperInvariant();
    }

    /// <summary>True only when the file is readable AND declares an .hmiproj but no TwinCAT
    /// project. Anything unclear keeps the classic "wait for the System Manager" path.</summary>
    public static bool IsHmiOnly(string slnPath)
    {
        try
        {
            var k = Classify(File.ReadAllText(slnPath));
            return k.HasHmi && !k.HasTwinCat;
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            return false;
        }
    }
}
